import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';

// Build the frontend, embed every emitted file, then compile one Bun executable.
const root = resolve(import.meta.dir, '..');
const node = Bun.which('node');
if (!node) throw new Error('Node.js is required to build the frontend.');
const vite = join(root, 'node_modules/vite/bin/vite.js');

const build = Bun.spawn([node, vite, 'build'], { cwd: root, stdout: 'inherit', stderr: 'inherit' });
if (await build.exited !== 0) process.exit(1);

const dist = join(root, 'dist');
const files: string[] = [];
const walk = (dir: string) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const file = join(dir, entry.name);
    if (entry.isDirectory()) walk(file); else if (entry.isFile()) files.push(file);
  }
};
walk(dist);
files.sort();

const imports: string[] = [];
const entries: string[] = [];
files.forEach((file, index) => {
  const specifier = relative(join(root, 'src/web'), file).split(sep).join('/');
  const key = '/' + relative(dist, file).split(sep).join('/');
  imports.push(`import f${index} from '${specifier}' with { type: 'file' };`);
  entries.push(`  '${key}': f${index},`);
});
const generated = join(root, 'src/web/embedded.gen.ts');
const stub = [
  '// Generated by scripts/build-binary.ts for `bun run build:binary`.',
  '// Source runs serve the dist directory instead, so this stays empty in development.',
  "export const assets: Record<string, string> = {};",
  '',
].join('\n');
writeFileSync(generated, [
  '// @ts-nocheck',
  '// Generated by scripts/build-binary.ts. Do not edit.',
  ...imports,
  '',
  'export const assets: Record<string, string> = {',
  ...entries,
  '};',
  '',
].join('\n'));

const out = join(root, 'release', 'dudu');
mkdirSync(join(root, 'release'), { recursive: true });
try {
  const compile = Bun.spawn([process.execPath, 'build', '--compile', join(root, 'src/main.ts'), '--outfile', out], { cwd: root, stdout: 'inherit', stderr: 'inherit' });
  const code = await compile.exited;
  if (code !== 0) process.exit(code);
} finally {
  // Keep the checked-in module resolvable for tsc; the compiled binary already
  // embedded the real assets above.
  writeFileSync(generated, stub);
}
console.log(`\nSingle binary: ${out}`);
